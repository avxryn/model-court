export const comparisonModeSchema = z.enum(['model', 'configuration'])
export type ComparisonMode = z.infer<typeof comparisonModeSchema>

/** One earlier turn of a conversation (D-39). */
export const transcriptMessageSchema = z.strictObject({
  role: z.enum(['user', 'assistant']),
  content: text(LIMITS.historyMessage, 'Message'),
})
export type TranscriptMessage = z.infer<typeof transcriptMessageSchema>

export const caseInputSchema = z.strictObject({
  key: uuid,
  title: text(LIMITS.caseTitle, 'Title'),
  input: text(LIMITS.caseInput, 'Input'),
  reference: text(LIMITS.caseReference, 'Reference'),
  expectedBehavior: text(LIMITS.caseExpectedBehavior, 'Expected behavior'),
  /**
   * Optional conversation so far (D-39): prior turns only, alternating, starting
   * with the user and ending with the assistant. `input` stays the final user turn.
   */
  messages: z
    .array(transcriptMessageSchema)
    .min(2, 'A conversation needs at least one user turn and one assistant reply')
    .max(LIMITS.historyMessages, `At most ${LIMITS.historyMessages} earlier messages`)
    .refine((messages) => messages.every((message, index) => message.role === (index % 2 === 0 ? 'user' : 'assistant')), 'Turns must alternate, starting with the user')
    .refine((messages) => messages.at(-1)?.role === 'assistant', 'The conversation so far must end with an assistant reply')
    .refine((messages) => messages.reduce((sum, message) => sum + codePointLength(message.content), 0) <= LIMITS.historyChars, `The conversation so far is at most ${LIMITS.historyChars.toLocaleString('en-US')} characters`)
    .optional(),
  /** Optional language tag for per-language results (D-36), e.g. "en" or "Spanish". */
  language: z.string().trim().min(1, 'Language cannot be blank').max(LIMITS.caseLanguage.max, `Language is at most ${LIMITS.caseLanguage.max} characters`).optional(),
})
export type CaseInput = z.infer<typeof caseInputSchema>

/** A party whose answers are generated by a model. `kind` is absent on drafts saved before D-38. */
export const modelConfigurationSchema = z.strictObject({
  kind: z.literal('model').optional(),
  key: uuid,
  label: text(LIMITS.configurationLabel, 'Label'),
  modelKey: z.string().min(1).max(80),
  systemPrompt: text(LIMITS.systemPrompt, 'System instructions'),
  maxOutputTokens: z.literal(LIMITS.maxOutputTokens),
})
export type ModelConfiguration = z.infer<typeof modelConfigurationSchema>

export const IMPORT_SOURCE_TYPES = ['human_baseline', 'transcript_export', 'other'] as const
export const provenanceSchema = z.strictObject({
  sourceType: z.enum(IMPORT_SOURCE_TYPES),
  description: text(LIMITS.provenanceDescription, 'Source description'),
  collectedOn: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Use a date like 2026-11-17').optional(),
  redacted: z.boolean(),
})
export type Provenance = z.infer<typeof provenanceSchema>

/** A party whose answers were written elsewhere and imported (D-38). Its texts live outside the draft. */
export const importedConfigurationSchema = z.strictObject({
  kind: z.literal('imported'),
  key: uuid,
  label: text(LIMITS.configurationLabel, 'Label'),
  provenance: provenanceSchema,
})
export type ImportedConfiguration = z.infer<typeof importedConfigurationSchema>

export const configurationSchema = z.union([modelConfigurationSchema, importedConfigurationSchema])
export type Configuration = z.infer<typeof configurationSchema>

export function isImported(configuration: { kind?: string }): configuration is ImportedConfiguration {
  return configuration.kind === 'imported'
}

/** Imported answer text: same character rules as other text, capped at the generated-output byte ceiling. */
export const importedTextSchema = text(LIMITS.importedText, 'Imported answer')
  .refine((value) => !hasDisallowedControlChars(value), 'Imported answer contains control characters')
  .refine((value) => utf8ByteLength(value) <= LIMITS.providerOutputBytes, `Imported answer exceeds ${LIMITS.providerOutputBytes / 1024} KiB`)

export const putImportsSchema = z.strictObject({
  items: z.array(z.strictObject({ caseKey: uuid, text: importedTextSchema })).min(1).max(LIMITS.maxCases),
  confirmMayShareWithJurors: z.literal(true),
})

function uniqueKeys(items: { key: string }[]): boolean {
  return new Set(items.map((item) => item.key)).size === items.length
}

export const casesSchema = z
  .array(caseInputSchema)
  .min(LIMITS.minCases, `Add at least ${LIMITS.minCases} case`)
  .max(LIMITS.maxCases, `At most ${LIMITS.maxCases} cases`)
  .refine(uniqueKeys, 'Case keys must be unique')

export const draftInputSchema = z
  .strictObject({
    comparisonMode: comparisonModeSchema,
    /** Absent means the default rubric (reference-qa-v1), so older drafts keep their snapshot hash. */
    rubricVersion: z.enum(RUBRIC_VERSIONS).optional(),
    cases: casesSchema,
    configurations: z
      .array(configurationSchema)
      .min(LIMITS.minConfigurationsPerRun, `Add at least ${LIMITS.minConfigurationsPerRun} configurations`)
      .max(LIMITS.maxConfigurationsPerRun, `At most ${LIMITS.maxConfigurationsPerRun} configurations`)
      .refine(uniqueKeys, 'Configuration keys must be unique'),
  })
  .refine((draft) => utf8ByteLength(JSON.stringify(draft)) <= LIMITS.draftJsonBytes, {
    message: 'Draft exceeds 96 KiB',
  })
export type DraftInput = z.infer<typeof draftInputSchema>
export type Draft = DraftInput & { schemaVersion: 1 }

