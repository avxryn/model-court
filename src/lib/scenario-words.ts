/** Plain words for scenario versions and party changes (spec 02 §3.1, D-68). */

import { PROVIDER_NAMES, type ProviderId } from '@/domain/registry'
import type { PartyChange, ScenarioDiff } from '@/domain/scenario'
import { plural } from '@/lib/format'

export type ModelName = (provider: string, modelId: string) => string

/** "OpenAI GPT-6 Luna" from the catalog, or the provider and the id that was sent. */
export function catalogModelName(models: ReadonlyArray<{ provider: string; modelId: string; label: string }> | undefined): ModelName {
  return (provider, modelId) => {
    const route = models?.find((model) => model.provider === provider && model.modelId === modelId)
    const name = PROVIDER_NAMES[provider as ProviderId] ?? provider
    return `${name} ${route?.label ?? modelId}`
  }
}

export function describePartyChange(change: PartyChange, modelName: ModelName): string {
  switch (change.kind) {
    case 'added':
      return `${change.label} added`
    case 'removed':
      return `${change.label} removed`
    case 'model':
      return `${change.label}: model ${modelName(change.from.provider, change.from.modelId)} → ${modelName(change.to.provider, change.to.modelId)}`
    case 'prompt':
      return `System instructions changed for ${change.label}`
    case 'source':
      return change.to === 'imported' ? `${change.label} now uses imported answers` : `${change.label} is now generated by a model`
    case 'provenance':
      return `Source description changed for ${change.label}`
    case 'answers':
      return `Imported answers changed for ${change.label}`
  }
}

/** One line per kind of change between a hearing's questions and the draft. */
export function describeScenarioDiff(diff: ScenarioDiff): string[] {
  const lines: string[] = []
  const titles = (items: ReadonlyArray<{ title: string }>) => items.map((item) => `“${item.title}”`).join(', ')
  if (diff.edited.length) lines.push(`${plural(diff.edited.length, 'question')} edited: ${titles(diff.edited)}`)
  if (diff.added.length) lines.push(`${plural(diff.added.length, 'question')} added: ${titles(diff.added)}`)
  if (diff.removed.length) lines.push(`${plural(diff.removed.length, 'question')} removed: ${titles(diff.removed)}`)
  if (diff.rubricChanged) lines.push('Rubric changed')
  if (diff.templateChanged) lines.push('Conversation format changed (a question gained or lost its conversation so far)')
  if (diff.kitChanged) lines.push('Task kit changed')
  return lines
}

/** "hearings 1, 2 and 4" / "hearing 3". */
export function hearingNumbers(numbers: readonly number[]): string {
  const sorted = [...numbers].sort((a, b) => a - b)
  if (sorted.length === 1) return `hearing ${sorted[0]}`
  return `hearings ${sorted.slice(0, -1).join(', ')} and ${sorted.at(-1)}`
}
